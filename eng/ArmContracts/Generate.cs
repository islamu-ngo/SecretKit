using System;
using System.Collections.Generic;
using System.IO;
using System.IO.Compression;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Xml.Linq;

namespace SecretKit.Build;

public static class Generate
{
    public static void Run(string assetsFile, string lockFile, string framework, string referenceFile,
        string bindingsFile, string output, Action<Stream, string, string, string> verifyPackage)
    {
        using var assets = JsonDocument.Parse(File.ReadAllBytes(assetsFile));
        using var locks = JsonDocument.Parse(File.ReadAllBytes(lockFile));
        var libraries = assets.RootElement.GetProperty("libraries");
        var resolved = assets.RootElement.GetProperty("targets").GetProperty(framework);
        var locked = locks.RootElement.GetProperty("dependencies").GetProperty(framework);
        var roots = assets.RootElement.GetProperty("packageFolders").EnumerateObject().Select(p => p.Name).ToArray();
        var references = File.ReadAllLines(referenceFile).Select(Path.GetFullPath).ToHashSet(StringComparer.Ordinal);
        var fields = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var group in File.ReadAllLines(bindingsFile).Select(line => line.Split('|')).GroupBy(row => row[1]))
        {
            string id = group.Key;
            var dependency = resolved.EnumerateObject().Single(p => p.Name.StartsWith(id + "/", StringComparison.Ordinal));
            string version = dependency.Name[(id.Length + 1)..];
            var lib = libraries.GetProperty(dependency.Name);
            var pin = locked.GetProperty(id);
            string hash = lib.GetProperty("sha512").GetString()!;
            ArmContractReader.VerifyLock(version, hash, pin.GetProperty("resolved").GetString()!, pin.GetProperty("contentHash").GetString()!);
            string asset = dependency.Value.GetProperty("compile").EnumerateObject()
                .Single(p => Path.GetFileName(p.Name) == id + ".dll").Name;
            string directory = roots.Select(root => Path.Combine(root, lib.GetProperty("path").GetString()!))
                .Single(dir => references.Contains(Path.GetFullPath(Path.Combine(dir, asset))));
            using var stream = File.OpenRead(Path.Combine(directory, $"{id.ToLowerInvariant()}.{version}.nupkg"));
            verifyPackage(stream, id, version, hash);
            stream.Position = 0;
            using var package = new ZipArchive(stream, ZipArchiveMode.Read);
            using var binary = package.Entries.Single(e => e.FullName == asset).Open();
            using var compile = File.OpenRead(Path.Combine(directory, asset));
            if (!SHA256.HashData(binary).AsSpan().SequenceEqual(SHA256.HashData(compile)))
                throw new InvalidDataException($"Resolved compile asset differs from locked SDK: {id}");
            string xml = Path.ChangeExtension(asset, ".xml");
            using var metadata = package.Entries.Single(e => e.FullName == xml).Open();
            var document = XDocument.Load(metadata);
            if (document.Root?.Element("assembly")?.Element("name")?.Value != id)
                throw new InvalidDataException($"Unexpected XML assembly identity for {id}");
            foreach (string[] row in group)
            {
                if (row.Length != 4 || !Regex.IsMatch(row[0], @"\A[A-Z][A-Za-z0-9]*\z"))
                    throw new InvalidDataException("Invalid symbolic ARM binding.");
                var contract = ArmContractReader.Select(document, row[3], row[2]);
                string[] values = [contract.RequestPath, contract.ApiVersion, id, version, hash, row[3], row[2]];
                fields.Add(row[0], $"    internal static readonly ArmMethodContract {row[0]} = new(" +
                    string.Join(", ", values.Select(s => JsonSerializer.Serialize(s))) + ");\n");
            }
        }
        if (fields.Count == 0) throw new InvalidDataException("No ARM method bindings.");
        string source = "// <auto-generated/>\nnamespace SecretKit.AzureKeyVault.Management;\n" +
            "internal sealed record ArmMethodContract(string RequestPath, string ApiVersion, string PackageId, " +
            "string PackageVersion, string ContentHash, string Member, string OperationId);\n" +
            "internal static class ArmMethodContracts\n{\n" + string.Concat(fields.Values) + "}\n";
        ArmContractReader.WriteChanged(output, source);
    }
}
